#!/usr/bin/env python3
"""Generate BENCHMARK_RESULTS.md from docs/benchmarks.yaml.

The benchmark report is never hand-typed. docs/benchmarks.yaml is generated
from the harness artifacts by scripts/extract_benchmarks.py; this renders the
human-readable report from it. To change a number, re-run the harness and
`make benchmark-facts`; to change prose, edit this script; then regenerate:

    python3 scripts/benchmark_report.py            # write BENCHMARK_RESULTS.md
    python3 scripts/benchmark_report.py --check     # fail if the report is stale

`--check` is wired into the docs-drift CI job. The report stamps benchmarks.yaml's
own measured date (not the wall clock) so a fresh render is byte-stable.
"""
from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
BENCHMARKS = REPO / "docs" / "benchmarks.yaml"
DOC = REPO / "BENCHMARK_RESULTS.md"


def render() -> str:
    b = yaml.safe_load(BENCHMARKS.read_text())
    m, h = b["_meta"], b["headline"]
    P = []

    P.append(
        "<!-- AUTO-GENERATED by scripts/benchmark_report.py from docs/benchmarks.yaml. "
        "DO NOT EDIT BY HAND. Regenerate: `make benchmark-report`. -->\n"
        "# Na0S Benchmark Report\n\n"
        f"**Artifact git_sha**: `{m['git_sha']}` · **Measured**: {m['measured']} · "
        f"**Threshold**: {m['threshold']}\n\n"
        "Numbers are generated from `docs/benchmarks.yaml` (itself extracted from "
        "`benchmarks/results/technique_analysis.json` by `scripts/extract_benchmarks.py`). "
        "Regenerate with `make benchmark-report`."
    )

    P.append(
        "## 1. Headline\n\n"
        "| Metric | Value | 95% CI |\n|---|---|---|\n"
        f"| Malicious recall | **{h['malicious_recall_pct']}%** "
        f"({h['malicious_detected']}/{h['malicious_total']}) | "
        f"{h['malicious_recall_ci_pct'][0]}–{h['malicious_recall_ci_pct'][1]}% |\n"
        f"| Benign false-positive rate | **{h['benign_fpr_pct']}%** "
        f"({h['benign_false_positives']}/{h['benign_total']}) | "
        f"{h['benign_fpr_ci_pct'][0]}–{h['benign_fpr_ci_pct'][1]}% |\n"
        f"| Evasion detection | **{h['evasion_detection_pct']}%** "
        f"({h['evasion_detected']}/{h['evasion_total']}) | — |\n\n"
        f"> {h['metrics_note']}"
    )

    P.append(
        "## 2. Methodology\n\n"
        f"The default `scan()` verdict at threshold {m['threshold']}. Recall and benign FPR "
        "are measured on independent pools (no shared prevalence), reported separately rather "
        "than as one F1. The threshold is the shipped default, not tuned to the eval set; every "
        "number is regenerated from a committed artifact; the hand-curated canary set is not a "
        "headline (see Appendix A)."
    )

    rows = "\n".join(
        f"| {cid} | {v['recall_pct']}% | {v['detected']}/{v['total']} |"
        for cid, v in b["per_category"].items()
    )
    weak = ", ".join(f"{cid} {v['recall_pct']}%" for cid, v in list(b["per_category"].items())[:5])
    P.append(
        "## 3. Per-category recall\n\n| Category | Recall | Detected |\n|---|---|---|\n" + rows +
        f"\n\nLowest five: {weak}. Detection-logic gaps, not wiring gaps."
    )

    erows = "\n".join(
        f"| {name} | {v['detection_pct']}% | {v['detected']}/{v['total']} |"
        for name, v in b["per_evasion_type"].items()
    )
    P.append(
        "## 4. Per-evasion-type detection\n\n| Transform | Detection | Detected |\n|---|---|---|\n" + erows
    )

    brows = "\n".join(
        f"| {name} | {v['fpr_pct']}% | {v['false_positives']}/{v['total']} |"
        for name, v in b["per_benign"].items()
    )
    P.append(
        "## 5. Per-benign-category false positives\n\n| Benign slice | FPR | FPs |\n|---|---|---|\n" + brows
    )

    ext = b["external"]
    d = ext["deepset"]
    P.append(
        "## 6. External public benchmarks (third-party)\n\n"
        "| Dataset | Samples | Recall | Precision | F1 | FPR |\n|---|---|---|---|---|---|\n"
        f"| deepset/prompt-injections | {d['n_samples']} | {d['recall_pct']}% | "
        f"{d['precision_pct']}% | {d['f1']} | {d['fpr_pct']}% |\n"
        f"| tatsu-lab/alpaca (benign) | {ext['alpaca']['n_samples']} | — | — | — | {ext['alpaca']['fpr_pct']}% |\n"
        f"| databricks/dolly (benign) | {ext['dolly']['n_samples']} | — | — | — | {ext['dolly']['fpr_pct']}% |\n\n"
        f"deepset recall ({d['recall_pct']}%) is a third-party data point, not a headline: a "
        f"stricter, narrower attack distribution with high precision ({d['precision_pct']}%)."
    )

    P.append(
        "## 7. Limitations\n\n"
        f"- Lowest-recall categories: {weak}.\n"
        "- No Recall@fixed-FPR, ROC/PR, confusion matrix, or over-defense metric yet; no public "
        "agent-injection benchmarks (AgentDojo, INJECAGENT, AdvBench, garak) reported.\n"
        "- Known-gap `xfail` tests document attacks the engine is expected to miss."
    )

    P.append(
        "## 8. Reproduction\n\n```bash\n"
        "make recall-harness     # regenerate benchmarks/results/technique_analysis.json\n"
        "make benchmark-facts    # regenerate docs/benchmarks.yaml from the artifact\n"
        "make benchmark-report   # regenerate this file from docs/benchmarks.yaml\n```"
    )

    P.append(
        "## Appendix A. Canary regression set (in-distribution)\n\n"
        "A 200-sample hand-curated set (`data/canary/canary_eval.csv`) scores ~100% and is kept "
        "as an internal regression tripwire. It is authored by us and in-distribution, so it is "
        "**not** a generalization estimate and is excluded from the headline."
    )

    return "\n\n---\n\n".join(P) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if the committed report is stale")
    args = ap.parse_args()

    out = render()
    if args.check:
        current = DOC.read_text() if DOC.exists() else ""
        if current != out:
            print("BENCHMARK_RESULTS.md is stale; run `make benchmark-report`.", file=sys.stderr)
            diff = difflib.unified_diff(current.splitlines(), out.splitlines(), "committed", "generated", lineterm="")
            print("\n".join(list(diff)[:30]), file=sys.stderr)
            return 1
        print("BENCHMARK_RESULTS.md is up to date.")
        return 0
    DOC.write_text(out)
    print(f"wrote {DOC.relative_to(REPO)} ({len(out)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
